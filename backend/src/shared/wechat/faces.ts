/** 把 emoji 换成微信表情占位符（如 😳 → `[发呆]`）。未命中的字符原样保留。 */
export function emojiToWechatFace(text: string): string {
  let out = text
  for (const [emoji, name] of EMOJI_TO_NAME) {
    if (out.includes(emoji)) out = out.split(emoji).join(`[${name}]`)
  }
  return out
}
