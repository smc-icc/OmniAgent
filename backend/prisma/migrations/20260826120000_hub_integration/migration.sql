-- ICC Integration Hub store (PostgreSQL schema hub)
CREATE SCHEMA IF NOT EXISTS hub;

CREATE TABLE IF NOT EXISTS hub.ingest_offset (
  source_key   text PRIMARY KEY,
  cursor       jsonb NOT NULL,
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hub.delivery (
  event_id     uuid NOT NULL,
  sink         text NOT NULL,
  status       text NOT NULL,
  attempts     int  NOT NULL DEFAULT 0,
  last_error   text,
  first_seen   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (event_id, sink)
);
CREATE INDEX IF NOT EXISTS hub_delivery_status_updated ON hub.delivery (status, updated_at);

CREATE TABLE IF NOT EXISTS hub.dlq (
  id           bigserial PRIMARY KEY,
  event_id     uuid NOT NULL,
  sink         text NOT NULL,
  event        jsonb NOT NULL,
  error        text NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  replayed_at  timestamptz
);

-- OmniAgent voicemail read model (ICC is source of facts; is_read/assignee are Omni-owned)
CREATE TABLE IF NOT EXISTS "icc_voicemails" (
  "id" BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "source_event_subject" TEXT NOT NULL,
  "vdn_id" INTEGER NOT NULL,
  "caller_number" TEXT,
  "callee_number" TEXT,
  "duration_sec" INTEGER NOT NULL DEFAULT 0,
  "audio_path" TEXT,
  "transcription" TEXT,
  "occurred_at" TIMESTAMP(3) NOT NULL,
  "is_read" BOOLEAN NOT NULL DEFAULT false,
  "read_by_user_id" INTEGER,
  "assignee_id" INTEGER,
  "deleted_at" TIMESTAMP(3),
  "raw" JSONB,
  "created_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updated_at" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "icc_voicemails_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "icc_voicemails_source_event_subject_key" ON "icc_voicemails"("source_event_subject");
CREATE INDEX IF NOT EXISTS "icc_voicemails_vdn_occurred_idx" ON "icc_voicemails"("vdn_id", "occurred_at" DESC);
